#include<stdio.h>
int main()
{
	printf("========== C ESCAPE SEQUENCE REFERENCE ============\n");
	printf("1. To print a double quote, write:\t \\\" \t \n");
	printf("2. To print a literal backlash, write:\t \\\\ \t \n");
	printf("3. To print a newline break, write:\t \\n"  "\n");
	printf("4. To insert a horizontal tab stop, write:\\t" "\n");
	printf("5. To print a percentage sign, write:\t  %%%% \t  " "\n");
	printf("==========================================================");

	
	return 0;
	
}
